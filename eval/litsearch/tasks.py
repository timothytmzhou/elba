def task_prompt(topic: str, aspects: list[str], out_path: str) -> str:
    facets = "; ".join(aspects)
    return (
        f"You are compiling the bibliography for a survey on {topic}. "
        f"Find {PAPERS_PER_TASK} published papers relevant to {topic}, together covering "
        f"all of these aspects: {facets}. "
        f"Write a BibTeX bibliography with one complete entry per paper "
        f"(authors, title, venue, year, and pages/volume/DOI where applicable) "
        f"to the file {out_path}. "
        f"Finally, print a short summary listing each paper's title and which "
        f"aspect it covers."
    )
